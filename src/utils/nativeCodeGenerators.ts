import { Project, Screen, ElementProperties } from '../types/builder';

/**
 * Generates Native iOS (SwiftUI) code for developers targeting iPhone 16 Pro and iOS devices.
 */
export function generateSwiftUICode(project: Project): string {
  const initialScreen = project.screens.find(s => s.isEntry) || project.screens[0];
  const screenNames = project.screens.map(s => {
    const clean = s.title.replace(/^\d+\.\s*/, '').replace(/[^a-zA-Z0-9]/g, '');
    return { id: s.id, varName: clean.charAt(0).toLowerCase() + clean.slice(1), structName: clean + 'View', title: s.title };
  });

  return `//
//  ${project.name.replace(/[^a-zA-Z0-9]/g, '')}App.swift
//  Generated by FlowCraft Pro Native Studio
//  Target Platform: Apple iOS (SwiftUI 5.0+ / Xcode 16)
//  Optimized for: iPhone 16 Pro & iOS Devices
//

import SwiftUI

enum ScreenDestination: String, Hashable, CaseIterable {
${project.screens.map(s => `    case ${s.id.replace(/[^a-zA-Z0-9_]/g, '')} = "${s.id}"`).join('\n')}
}

@main
struct FlowCraftApp: App {
    var body: some Scene {
        WindowGroup {
            MainContainerView()
                .preferredColorScheme(.dark)
        }
    }
}

struct MainContainerView: View {
    @State private var currentScreen: ScreenDestination = .${initialScreen?.id.replace(/[^a-zA-Z0-9_]/g, '') || 'screen_onboarding'}
    @State private var navigationPath: [ScreenDestination] = []
    @State private var toastMessage: String? = nil
    
    var body: some View {
        NavigationStack(path: $navigationPath) {
            ZStack {
                Color(hex: "${initialScreen?.backgroundColor || '#0F172A'}").ignoresSafeArea()
                
                VStack(spacing: 0) {
                    // Active View Controller
                    switch currentScreen {
${project.screens.map(s => `                    case .${s.id.replace(/[^a-zA-Z0-9_]/g, '')}:
                        ${s.title.replace(/^\d+\.\s*/, '').replace(/[^a-zA-Z0-9]/g, '')}Screen(
                            onNavigate: { target in
                                navigationPath.append(target)
                                currentScreen = target
                            },
                            onBack: {
                                if !navigationPath.isEmpty {
                                    navigationPath.removeLast()
                                    currentScreen = navigationPath.last ?? .${initialScreen?.id.replace(/[^a-zA-Z0-9_]/g, '')}
                                }
                            },
                            onToast: { msg in
                                withAnimation { toastMessage = msg }
                                DispatchQueue.main.asyncAfter(deadline: .now() + 3) {
                                    withAnimation { toastMessage = nil }
                                }
                            }
                        )`).join('\n')}
                    }
                }
                
                // Toast notification overlay
                if let msg = toastMessage {
                    VStack {
                        HStack(spacing: 10) {
                            Image(systemName: "bell.fill")
                                .foregroundColor(.blue)
                            Text(msg)
                                .font(.footnote.weight(.semibold))
                                .foregroundColor(.white)
                        }
                        .padding(.horizontal, 16)
                        .padding(.vertical, 12)
                        .background(Color(hex: "#1E293B").opacity(0.95))
                        .clipShape(RoundedRectangle(cornerRadius: 16))
                        .overlay(
                            RoundedRectangle(cornerRadius: 16)
                                .stroke(Color.white.opacity(0.1), lineWidth: 1)
                        )
                        .shadow(radius: 12)
                        .padding(.top, 50)
                        
                        Spacer()
                    }
                    .transition(.move(edge: .top).combined(with: .opacity))
                }
            }
        }
    }
}

// MARK: - Individual Screen Views
${project.screens.map(screen => generateSwiftUIScreen(screen)).join('\n\n')}

// MARK: - Color Hex Extension
extension Color {
    init(hex: String) {
        let hex = hex.trimmingCharacters(in: CharacterSet.alphanumerics.inverted)
        var int: UInt64 = 0
        Scanner(string: hex).scanHexInt64(&int)
        let a, r, g, b: UInt64
        switch hex.count {
        case 3: // RGB (12-bit)
            (a, r, g, b) = (255, (int >> 8) * 17, (int >> 4 & 0xF) * 17, (int & 0xF) * 17)
        case 6: // RGB (24-bit)
            (a, r, g, b) = (255, int >> 16, int >> 8 & 0xFF, int & 0xFF)
        case 8: // ARGB (32-bit)
            (a, r, g, b) = (int >> 24, int >> 16 & 0xFF, int >> 8 & 0xFF, int & 0xFF)
        default:
            (a, r, g, b) = (1, 1, 1, 0)
        }
        self.init(
            .sRGB,
            red: Double(r) / 255,
            green: Double(g) / 255,
            blue:  Double(b) / 255,
            opacity: Double(a) / 255
        )
    }
}

#Preview {
    MainContainerView()
        .preferredColorScheme(.dark)
}
`;
}

function generateSwiftUIScreen(screen: Screen): string {
  const structName = screen.title.replace(/^\d+\.\s*/, '').replace(/[^a-zA-Z0-9]/g, '') + 'Screen';

  return `struct ${structName}: View {
    var onNavigate: (ScreenDestination) -> Void
    var onBack: () -> Void
    var onToast: (String) -> Void
    
    @State private var inputText: String = ""
    @State private var isToggled: Bool = true
    
    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 14) {
${screen.elements.map(el => generateSwiftUIElement(el)).join('\n')}
            }
            .padding(.horizontal, 20)
            .padding(.vertical, 16)
        }
    }
}`;
}

function generateSwiftUIElement(el: ElementProperties): string {
  switch (el.type) {
    case 'header':
      return `                // Header: ${el.label}
                HStack {
                    ${el.hasAction ? `Button(action: onBack) {
                        Image(systemName: "chevron.left")
                            .font(.system(size: 16, weight: .bold))
                            .foregroundColor(.white)
                            .padding(8)
                            .background(Color.white.opacity(0.1))
                            .clipShape(Circle())
                    }` : ''}
                    VStack(alignment: .leading, spacing: 2) {
                        Text("${el.label}")
                            .font(.headline.weight(.bold))
                            .foregroundColor(.white)
                        ${el.helperText ? `Text("${el.helperText}").font(.caption).foregroundColor(.gray)` : ''}
                    }
                    Spacer()
                    Button(action: { onToast("Notifications are synced") }) {
                        Image(systemName: "bell.fill")
                            .font(.subheadline)
                            .foregroundColor(.gray)
                    }
                }
                .padding(.bottom, 6)`;

    case 'image_banner':
      return `                // Banner Visual
                VStack(alignment: .leading, spacing: 8) {
                    ${el.imageUrl ? `AsyncImage(url: URL(string: "${el.imageUrl}")) { phase in
                        if let image = phase.image {
                            image.resizable().aspectRatio(contentMode: .fill)
                        } else {
                            Rectangle().fill(Color.blue.opacity(0.2))
                        }
                    }
                    .frame(height: 150)
                    .clipShape(RoundedRectangle(cornerRadius: 16))` : ''}
                    Text("${el.label}")
                        .font(.title3.weight(.bold))
                        .foregroundColor(.white)
                    ${el.helperText ? `Text("${el.helperText}").font(.subheadline).foregroundColor(.gray)` : ''}
                }`;

    case 'card':
      return `                // Card Component: ${el.label}
                VStack(alignment: .leading, spacing: 8) {
                    HStack {
                        Image(systemName: "${mapToSFSymbol(el.icon)}")
                            .font(.headline)
                            .foregroundColor(.blue)
                        Text("${el.label}")
                            .font(.subheadline.weight(.semibold))
                            .foregroundColor(.white)
                    }
                    ${el.helperText ? `Text("${el.helperText}").font(.caption).foregroundColor(.gray)` : ''}
                }
                .padding(16)
                .frame(maxWidth: .infinity, alignment: .leading)
                .background(Color(hex: "#1E293B").opacity(0.8))
                .clipShape(RoundedRectangle(cornerRadius: 16))
                .overlay(RoundedRectangle(cornerRadius: 16).stroke(Color.white.opacity(0.08), lineWidth: 1))`;

    case 'badge':
      return `                // Badge: ${el.label}
                HStack(spacing: 6) {
                    Image(systemName: "${mapToSFSymbol(el.icon)}")
                        .font(.system(size: 11, weight: .bold))
                    Text("${el.label}")
                        .font(.caption2.weight(.bold))
                }
                .padding(.horizontal, 10)
                .padding(.vertical, 5)
                .foregroundColor(.green)
                .background(Color.green.opacity(0.15))
                .clipShape(Capsule())`;

    case 'button': {
      const targetScreen = el.targetScreenId?.replace(/[^a-zA-Z0-9_]/g, '') || '';
      return `                // Action Button: ${el.label}
                Button(action: {
                    ${el.actionType === 'navigate' && targetScreen ? `onNavigate(.${targetScreen})` : ''}
                    ${el.actionType === 'back' ? `onBack()` : ''}
                    ${el.actionType === 'toast' ? `onToast("${el.toastMessage || 'Action performed'}")` : ''}
                }) {
                    HStack {
                        Text("${el.label}")
                            .fontWeight(.bold)
                        ${el.icon ? `Image(systemName: "${mapToSFSymbol(el.icon)}")` : ''}
                    }
                    .frame(maxWidth: .infinity)
                    .padding(.vertical, 14)
                    .foregroundColor(.white)
                    .background(${el.variant === 'primary' ? 'Color.blue' : el.variant === 'success' ? 'Color.green' : 'Color.white.opacity(0.1)'})
                    .clipShape(RoundedRectangle(cornerRadius: 16))
                    .shadow(color: Color.blue.opacity(0.3), radius: 6, y: 3)
                }`;
    }

    case 'input':
      return `                // Text Input Field
                VStack(alignment: .leading, spacing: 6) {
                    Text("${el.label}").font(.caption.weight(.semibold)).foregroundColor(.gray)
                    HStack {
                        Image(systemName: "${mapToSFSymbol(el.icon)}")
                            .foregroundColor(.gray)
                        TextField("${el.placeholder || 'Enter value'}", text: $inputText)
                            .foregroundColor(.white)
                    }
                    .padding(12)
                    .background(Color(hex: "#1E293B"))
                    .clipShape(RoundedRectangle(cornerRadius: 12))
                }`;

    case 'metric':
      return `                // Metric Card
                VStack(alignment: .leading, spacing: 6) {
                    Text("${el.label}").font(.caption).foregroundColor(.gray)
                    Text("${el.metricValue || '$28,450.00'}")
                        .font(.title.weight(.bold))
                        .foregroundColor(.white)
                    if let change = "${el.metricChange || '+12.4%'}" as String? {
                        Text(change).font(.caption.weight(.bold)).foregroundColor(.green)
                    }
                }
                .padding(16)
                .frame(maxWidth: .infinity, alignment: .leading)
                .background(Color(hex: "#1E293B"))
                .clipShape(RoundedRectangle(cornerRadius: 16))`;

    case 'toggle':
      return `                // Settings Toggle
                Toggle("${el.label}", isOn: $isToggled)
                    .font(.subheadline.weight(.semibold))
                    .foregroundColor(.white)
                    .tint(.blue)
                    .padding(.vertical, 4)`;

    case 'tabbar':
      return `                // Navigation Tab Bar
                HStack {
                    ForEach(["Home", "Cards", "Transfer", "Settings"], id: \\.self) { tab in
                        Spacer()
                        VStack(spacing: 4) {
                            Image(systemName: tab == "Home" ? "house.fill" : tab == "Cards" ? "creditcard.fill" : "gearshape.fill")
                                .font(.system(size: 18))
                            Text(tab).font(.caption2)
                        }
                        .foregroundColor(tab == "Home" ? .blue : .gray)
                        Spacer()
                    }
                }
                .padding(.vertical, 10)
                .background(Color(hex: "#1E293B").opacity(0.95))
                .clipShape(RoundedRectangle(cornerRadius: 20))`;

    default:
      return `                // Generic Element: ${el.label}
                Text("${el.label}").foregroundColor(.white)`;
  }
}

function mapToSFSymbol(icon?: string): string {
  if (!icon) return 'sparkles';
  switch (icon) {
    case 'arrow-right': return 'arrow.right';
    case 'shield-check': return 'shield.lefthalf.filled';
    case 'lock': return 'lock.fill';
    case 'key': return 'key.fill';
    case 'send': return 'paperplane.fill';
    case 'home': return 'house.fill';
    case 'credit-card': return 'creditcard.fill';
    case 'settings': return 'gearshape.fill';
    case 'bell': return 'bell.fill';
    case 'zap': return 'bolt.fill';
    case 'check': return 'checkmark';
    case 'check-circle': return 'checkmark.circle.fill';
    case 'server': return 'server.rack';
    default: return 'circle.fill';
  }
}

